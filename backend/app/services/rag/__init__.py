"""RAG pipeline: chunking, embedding, vector search, and answer generation.

This module ties together:
1. PDF→text via PyMuPDF.
2. Text→chunks via configurable size/overlap.
3. Chunks→embeddings via Sentence Transformers (local).
4. Embeddings→Qdrant vector storage with ownership filter.
5. Question→context retrieval from Qdrant.
6. Context→KIE LLM generation with forced citations.
"""
from __future__ import annotations

import logging
from dataclasses import dataclass, field
from typing import List, Optional, Tuple

logger = logging.getLogger(__name__)


@dataclass
class Chunk:
    """A piece of extracted document text with its metadata."""
    chunk_id: str
    text: str
    document_id: str  # server-controlled, not user-supplied
    owner_id: int
    page_number: int
    chunk_index: int
    source_filename: str
    text_hash: str = ""
    embedding: Optional[List[float]] = None  # Embedding vector, generated by Sentence Transformers


def chunk_text(
    text: str,
    chunk_size: int = 1000,
    chunk_overlap: int = 150,
) -> List[Chunk]:
    """Split *text* into overlapping chunks and return ``Chunk`` named tuples.

    Overlap ensures no critical context is lost at chunk boundaries.
    Chunk IDs are deterministic within the owning document.
    """
    if not text or not text.strip():
        return []

    words = text.split()
    if len(words) <= chunk_size:
        return [Chunk(
            chunk_id=f"0_{0}",
            text=text,
            document_id="",
            owner_id=0,
            page_number=0,
            chunk_index=0,
            source_filename="",
        )]

    chunks: List[Chunk] = []
    start = 0
    idx = 0
    while start < len(words):
        end = min(start + chunk_size, len(words))
        piece_words = words[start:end]
        piece_text = " ".join(piece_words)
        chunk_id = f"{idx}_{start}"
        chunks.append(Chunk(
            chunk_id=chunk_id,
            text=piece_text,
            document_id="",
            owner_id=0,
            page_number=0,
            chunk_index=idx,
            source_filename="",
        ))
        start = end - chunk_overlap if end - chunk_overlap > start else end
        if start >= len(words):
            break
        idx += 1

    return chunks


# Embedding model singleton
_embedding_model = None


def get_embedding_model():
    """Lazy load the Sentence Transformers embedding model."""
    global _embedding_model
    if _embedding_model is None:
        try:
            from sentence_transformers import SentenceTransformer
            from ...core.config import settings
            _embedding_model = SentenceTransformer(
                settings.embedding_model,
                device=settings.embedding_device
            )
        except ImportError as e:
            logger.warning("Sentence Transformers not installed: %s", e)
            raise
        except Exception as e:
            logger.warning("Failed to load embedding model: %s", e)
            raise
    return _embedding_model


def generate_embeddings(texts: List[str]) -> List[List[float]]:
    """Generate embeddings for a list of texts using the Sentence Transformers model."""
    if not texts:
        return []
    try:
        model = get_embedding_model()
        embeddings = model.encode(texts, batch_size=32, show_progress_bar=False)
        return embeddings.tolist()
    except ImportError:
        logger.warning("Sentence Transformers not available")
        raise
    except Exception as e:
        logger.warning("Failed to generate embeddings: %s", e)
        raise

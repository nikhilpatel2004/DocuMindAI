"""Vector store operations over Qdrant.

Uses the `qdrant-client` package. All searches are scoped to ``owned``
document IDs — never a global free-text search across all users.
"""
from __future__ import annotations

import logging
from pathlib import Path
from typing import List, Optional

from ...core.config import settings
from ..rag import Chunk

logger = logging.getLogger(__name__)

CHUNK_METADATA_FIELDS = [
    "document_id", "owner_id", "page_number", "chunk_index",
    "source_filename", "text_hash"
]

QDRANT_PAYLOAD_LIMIT_KEYS = {
    "document_id": "TEXT",
    "owner_id": "INTEGER",
    "page_number": "INTEGER",
    "chunk_index": "INTEGER",
    "source_filename": "TEXT",
    "text_hash": "TEXT",
}


# Qdrant client singleton
_qdrant_client = None
_qdrant_collection_initialized = False


def get_qdrant_client():
    """Lazy initialize the Qdrant client.

    Two modes are supported:
    * embedded — ``QDRANT_LOCAL_PATH`` is set: Qdrant runs inside this process
      with on-disk storage, so no Qdrant server is needed.
    * server — ``QDRANT_LOCAL_PATH`` is empty: connect to the Qdrant instance
      at ``QDRANT_URL``.
    """
    global _qdrant_client
    if _qdrant_client is None:
        try:
            from qdrant_client import QdrantClient

            if settings.qdrant_local_path:
                storage = Path(settings.qdrant_local_path)
                storage.mkdir(parents=True, exist_ok=True)
                logger.info("Using embedded Qdrant storage at %s", storage)
                _qdrant_client = QdrantClient(path=str(storage))
            else:
                _qdrant_client = QdrantClient(url=settings.qdrant_url)
        except ImportError as e:
            logger.warning("Qdrant client not installed: %s", e)
            raise
        except Exception as e:
            logger.warning("Failed to initialize Qdrant client: %s", e)
            raise
    return _qdrant_client


def ensure_collection_exists():
    """Ensure the Qdrant collection exists with the correct configuration."""
    global _qdrant_collection_initialized
    if _qdrant_collection_initialized:
        return
    try:
        client = get_qdrant_client()
        from ...core.config import settings
        from qdrant_client.http import models as rest

        # Check if collection exists
        collections = client.get_collections().collections
        collection_names = [c.name for c in collections]
        if settings.qdrant_collection not in collection_names:
            # Create collection
            client.create_collection(
                collection_name=settings.qdrant_collection,
                vectors_config=rest.VectorParams(
                    size=384,  # Default for all-MiniLM-L6-v2
                    distance=rest.Distance.COSINE,
                ),
            )
            logger.info("Created Qdrant collection: %s", settings.qdrant_collection)
        else:
            logger.debug("Qdrant collection %s already exists", settings.qdrant_collection)
        _qdrant_collection_initialized = True
    except ImportError:
        logger.warning("Qdrant client not available")
        raise
    except Exception as e:
        logger.warning("Failed to ensure Qdrant collection exists: %s", e)
        raise


def upsert_chunks(chunks: List[Chunk]) -> None:
    """Insert or update chunks in the Qdrant vector store.
    Each chunk must have been annotated with document_id, owner_id, page_number, chunk_index, source_filename, and text_hash.
    Embeddings are generated by the caller (or by the RAG service) and must be set on the chunk's `embedding` attribute.
    """
    if not chunks:
        return
    try:
        client = get_qdrant_client()
        ensure_collection_exists()
        from qdrant_client.http import models as rest

        points = []
        for chunk in chunks:
            if not hasattr(chunk, 'embedding') or chunk.embedding is None:
                raise ValueError(f"Chunk {chunk.chunk_id} is missing embedding")
            point = rest.PointStruct(
                id=hash(chunk.chunk_id) % (2**31),  # Simple hash to int ID
                vector=chunk.embedding,
                payload={
                    "chunk_id": chunk.chunk_id,
                    "text": chunk.text,
                    "document_id": chunk.document_id,
                    "owner_id": chunk.owner_id,
                    "page_number": chunk.page_number,
                    "chunk_index": chunk.chunk_index,
                    "source_filename": chunk.source_filename,
                    "text_hash": chunk.text_hash,
                }
            )
            points.append(point)

        client.upsert(
            collection_name=settings.qdrant_collection,
            points=points
        )
        logger.info("Upserted %d chunks to Qdrant collection %s", len(chunks), settings.qdrant_collection)
    except ImportError:
        logger.warning("Qdrant client not available")
        raise
    except Exception as e:
        logger.warning("Failed to upsert chunks to Qdrant: %s", e)
        raise


def search_chunks(query_embedding: List[float], owner_id: int, document_ids: List[str], limit: int = 5) -> List[tuple[Chunk, float]]:
    """Search for chunks similar to the query embedding, filtered by owner_id and document_ids.
    Returns a list of (Chunk, score) tuples, sorted by score descending.
    """
    if not query_embedding:
        return []
    try:
        client = get_qdrant_client()
        ensure_collection_exists()
        from qdrant_client.http import models as rest

        # Build filter
        must_conditions = [
            rest.FieldCondition(
                key="owner_id",
                match=rest.MatchValue(value=owner_id)
            )
        ]
        if document_ids:
            must_conditions.append(
                rest.FieldCondition(
                    key="document_id",
                    match=rest.MatchAny(any=document_ids)
                )
            )
        filter_condition = rest.Filter(must=must_conditions) if must_conditions else None

        # ``search`` was removed in qdrant-client >= 1.15 — query_points is the
        # supported equivalent and works in both server and embedded mode.
        response = client.query_points(
            collection_name=settings.qdrant_collection,
            query=query_embedding,
            query_filter=filter_condition,
            limit=limit,
            with_payload=True,
            with_vectors=False
        )

        results: List[tuple[Chunk, float]] = []
        for hit in response.points:
            payload = hit.payload
            chunk = Chunk(
                chunk_id=payload.get("chunk_id", str(hit.id)),
                text=payload.get("text", ""),
                document_id=payload.get("document_id", ""),
                owner_id=payload.get("owner_id", 0),
                page_number=payload.get("page_number", 0),
                chunk_index=payload.get("chunk_index", 0),
                source_filename=payload.get("source_filename", ""),
                text_hash=payload.get("text_hash", "")
            )
            score = hit.score
            results.append((chunk, score))

        # Sort by score descending (already sorted by Qdrant, but just in case)
        results.sort(key=lambda x: x[1], reverse=True)
        logger.info("Search returned %d results", len(results))
        return results
    except ImportError:
        logger.warning("Qdrant client not available")
        raise
    except Exception as e:
        logger.warning("Failed to search Qdrant: %s", e)
        raise


def reassign_owner_id(new_owner_id: int) -> None:
    """Rewrite the ``owner_id`` payload on every stored chunk.

    Used once when the app switches to the single-local-user model so that
    vectors created under historical accounts stay searchable.
    """
    client = get_qdrant_client()
    ensure_collection_exists()
    from qdrant_client.http import models as rest

    client.set_payload(
        collection_name=settings.qdrant_collection,
        payload={"owner_id": int(new_owner_id)},
        points=rest.Filter(),
        wait=True,
    )
    logger.info(
        "Reassigned vectors in %s to owner_id=%s",
        settings.qdrant_collection,
        new_owner_id,
    )


def delete_chunks_for_document(document_id: str, owner_id: int) -> None:
    """Delete all vector points belonging to document_id for owner_id."""
    try:
        client = get_qdrant_client()
        ensure_collection_exists()
        from qdrant_client.http import models as rest

        client.delete(
            collection_name=settings.qdrant_collection,
            points_selector=rest.Filter(
                must=[
                    rest.FieldCondition(key="document_id", match=rest.MatchValue(value=document_id)),
                    rest.FieldCondition(key="owner_id", match=rest.MatchValue(value=owner_id)),
                ]
            ),
        )
        logger.info("Deleted chunks for document %s (owner=%s) from Qdrant", document_id, owner_id)
    except Exception as exc:
        logger.warning("Failed to delete Qdrant chunks for document %s: %s", document_id, exc)
